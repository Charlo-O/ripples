"""Slice the CC0 Freesound recordings into clean one-shot clips and embed them
as base64 in ../sfx.js, so the page plays sound with no server and no fetch.

Onset timings are taken from the original record/sound.py analysis.
Run:  python tools/prep_sfx.py   (needs ffmpeg on PATH)
"""
import base64, json, subprocess, tempfile, os
from pathlib import Path

SRC = Path(r"C:/ali/paper/Paper/Paper/record/sfx")
OUT = Path(__file__).resolve().parent.parent / "sfx.js"

def slice_clip(name, t0, t1, hp=None, fin=0.003, fout=0.02):
    filters = []
    if hp:
        filters += [f"highpass=f={hp}"] * 2
    a = max(0.0, t0)
    filters.append(f"afade=t=in:st=0:d={fin}")
    filters.append(f"afade=t=out:st={max(0.0,(t1-t0)-fout)}:d={fout}")
    af = ",".join(filters)
    with tempfile.TemporaryDirectory() as d:
        mp3 = os.path.join(d, "c.mp3")
        subprocess.run([
            "ffmpeg", "-v", "error", "-y",
            "-ss", f"{a:.4f}", "-t", f"{t1-t0:.4f}", "-i", str(SRC / name),
            "-af", af, "-ac", "1", "-ar", "44100", "-b:a", "96k", mp3
        ], check=True)
        return base64.b64encode(Path(mp3).read_bytes()).decode("ascii")

DROPS = "fs_351623_Water-Drops-wav.mp3"
BRUSH = "fs_482891_painting_1-aif.mp3"
PENCIL = "fs_802604_Pencil-Writing-and-Taps.mp3"
BUB = "fs_464187_burbujas_bubbles-wav.mp3"

bank = {
    # pitched water drops: (file, onset, dominant Hz)
    "drop": [(DROPS, t, hz) for t, hz in
             [(0.135, 2546), (0.300, 2223), (0.475, 1313), (1.675, 2350),
              (2.045, 1868), (3.310, 1913), (3.635, 2553), (4.255, 1870)]],
    "bubble": [(BUB, t, hz) for t, hz in
               [(2.500, 624), (1.990, 630), (8.675, 727), (9.285, 778),
                (14.060, 859), (6.295, 704)]],
}

out = {"drop": [], "bubble": [], "brush": [], "pencil": []}
for key, specs in bank.items():
    for f, t, hz in specs:
        hp = 250 if key == "drop" else 200
        b = slice_clip(f, t - 0.006, t + (0.14 if key == "drop" else 0.09), hp=hp)
        out[key].append({"hz": hz, "b": b})
        print(key, t, hz, len(b))

for t in (5.850, 16.470, 10.925, 15.275, 6.250):
    out["brush"].append({"b": slice_clip(BRUSH, t - 0.005, t + 0.12, hp=150)})
    print("brush", t)
for t in (2.125, 34.250, 3.115, 0.195):
    out["pencil"].append({"b": slice_clip(PENCIL, t - 0.005, t + 0.06, hp=1500)})
    print("pencil", t)

# single one-shots: name -> (file, t0, t1, hp, fout, hz)
singles = {
    "round":    ("fs_273870_water-drop-1-aif.mp3", 0.0, 0.38, 250, 0.05, 1097),
    "plop":     ("fs_165206_Water-Drop-Sound-wav.mp3", 0.0, 0.25, 150, 0.03, 668),
    "dark":     ("fs_337525_Water-Drop-Dark.mp3", 0.11, 0.58, 150, 0.12, 1372),
    "sparkle":  ("fs_321490_Tiny-Splash.mp3", 0.15, 0.30, 700, 0.05, 0),
    "twodrip":  ("fs_166986_Two_Drips_001-wav.mp3", 0.0, 0.12, 250, 0.02, 2131),
    "splash":   ("fs_50623_water_splash_10shots-wav.mp3", 0.02, 0.48, 150, 0.08, 0),
    "stamp_a":  ("fs_362624_Stamp.mp3", 0.02, 0.32, None, 0.05, 0),
    "stamp_b":  ("fs_362622_Stamp.mp3", 0.02, 0.40, None, 0.06, 0),
}
for k, (f, t0, t1, hp, fo, hz) in singles.items():
    out[k] = {"hz": hz, "b": slice_clip(f, t0, t1, hp=hp, fout=fo)}
    print(k, len(out[k]["b"]))

js = "/* Auto-generated by tools/prep_sfx.py — CC0 Freesound one-shots, base64 MP3. */\n"
js += "window.SFX_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n"
OUT.write_text(js, encoding="utf-8")
print("wrote", OUT, f"{OUT.stat().st_size/1024:.0f} KB")